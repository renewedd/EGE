#Программа должна искать в строке последовательности 12, 322 и 222. Если найдено 12, она заменяет первое такое
# вхождение на 2. Если найдено 322, она заменяет первое такое вхождение на 21. Если найдено 222, она заменяет первое такое вхождение на 3. Цикл продолжается, пока в строке встречается хотя бы одна из этих цепочек.
#На вход приведённой выше программе поступает строка, начинающаяся с цифры «1», а затем содержащая n цифр «2» (3 < n
# < 10 000). Определите наименьшее значение n, при котором сумма цифр в строке, получившейся в результате выполнения программы, равна 15.

for n in range(3,10000):
    s = "3" + "1" * n
    while "12" in s or "322" in s or "222" in s:
        if "12" in s:
            s = s.replace("12", "2",1)
        elif "322" in s:
            s = s.replace("322","21",1)
        elif "222" in s:
            s = s.replace("222","3",1)








