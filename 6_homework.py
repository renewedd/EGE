#Если найдено 211, она заменяет первое такое вхождение на 13. Если найдено 1111, она заменяет первое такое вхождение на 2.
#Цикл продолжается, пока в строке встречается хотя бы одна из этих цепочек.
#На вход приведённой выше программе поступает строка, начинающаяся с цифры «3», а затем содержащая n цифр «1» (3 < n
# < 10 000).
#Определите наименьшее значение n, при котором сумма цифр в строке, получившейся в результате выполнения программы,
# равна 15.
for n in range(4,10000):
    s = "3" + "1" * n
    while "31" in s or "211" in s or "1111" in s:
        if "31" in s:
            s = s.replace("31","1",1)
        elif "211" in s:
            s = s.replace("211", "13", 1)
        elif "1111" in s:
            s = s.replace("1111", "2", 1)

